-- Run by the local Postgres test harness inside a rolled-back transaction.
do $$
declare
  owner_uid uuid := gen_random_uuid();
  viewer_uid uuid := gen_random_uuid();
  editor_uid uuid := gen_random_uuid();
  stranger_uid uuid := gen_random_uuid();
  eid uuid;
  version_now bigint;
  code text;
  old_code text;
  photo text;
  result jsonb;
  state jsonb := '{"event":"Collaboration rollback check","date":"2026-10-31","timezone":"Asia/Dhaka","volunteers":[],"shifts":[],"schedule":{}}';
begin
  insert into auth.users(id, email, raw_user_meta_data) values
    (owner_uid, owner_uid::text || '@example.test', '{"name":"Owner test","phone":"+8801700000001"}'),
    (viewer_uid, viewer_uid::text || '@example.test', '{"name":"Viewer test","phone":"+8801700000002"}'),
    (editor_uid, editor_uid::text || '@example.test', '{"name":"Editor test"}'),
    (stranger_uid, stranger_uid::text || '@example.test', '{"name":"Stranger test"}');
  photo := viewer_uid::text || '/' || gen_random_uuid()::text || '.jpg';
  update public.shiftrescue_profiles set avatar_path = photo where id = viewer_uid;
  set local role authenticated;
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  result := public.shiftrescue_save_event(null, 0, state, null); eid := (result->>'id')::uuid;
  assert result->>'role' = 'owner', 'Owner role missing';
  state := state || '{"volunteers":[{"id":"v1","name":"Test volunteer","skills":[],"availability":[[0,1440]],"maxHours":24}],"shifts":[{"id":"s1","station":"Test desk","start":0,"end":60,"required":1,"skills":[]}],"schedule":{"s1":["v1"]}}';
  perform public.shiftrescue_save_event(eid, (result->>'version')::bigint, state, null);
  result := public.shiftrescue_event_sharing(eid); code := result->>'code';
  assert length(code) = 12, 'Missing unique code';
  begin perform * from shiftrescue_private.event_codes; raise exception 'Private codes exposed'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub', viewer_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', viewer_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid) is null, 'Unapproved read exposed';
  assert public.shiftrescue_event_status(eid) is null, 'Unapproved status exposed';
  result := public.shiftrescue_request_access(code, 'editor'); assert result->>'status' = 'pending';
  result := public.shiftrescue_request_access(code, 'editor'); assert result->>'status' = 'pending', 'Duplicate request is not idempotent';
  assert public.shiftrescue_load_event(eid) is null, 'A code granted access without approval';
  assert (select count(*) from public.shiftrescue_profiles where id = owner_uid) = 0, 'Private contacts exposed';
  begin perform public.shiftrescue_event_sharing(eid); raise exception 'Requester managed sharing'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  result := public.shiftrescue_event_sharing(eid);
  assert jsonb_array_length(result->'requests') = 1, 'Duplicate pending request';
  assert (select count(*) from public.shiftrescue_profiles where id = viewer_uid) = 0, 'Owner gained direct access to private contact fields';
  assert result->'requests'->0->>'name' = 'Viewer test';
  assert not (result->'requests'->0 ? 'phone') and not (result->'requests'->0 ? 'email'), 'Contact data in preview';
  assert shiftrescue_private.can_read_shared_avatar(photo), 'Owner cannot preview pending photo';
  assert (public.shiftrescue_requester_avatar(eid, viewer_uid)->>'avatarPath') = photo;
  assert (public.shiftrescue_event_status(eid)->>'pendingRequests')::integer = 1;
  perform public.shiftrescue_decide_access(eid, viewer_uid, 'viewer');
  perform set_config('request.jwt.claim.sub', viewer_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', viewer_uid, 'is_anonymous', false)::text, true);
  result := public.shiftrescue_load_event(eid); assert result->>'role' = 'viewer'; version_now := (result->>'version')::bigint;
  begin perform public.shiftrescue_save_event(eid, version_now, state, null); raise exception 'Viewer saved'; exception when insufficient_privilege then null; end;
  begin update public.shiftrescue_events set name = 'Forbidden viewer change' where id = eid; assert not found, 'Viewer direct write'; exception when insufficient_privilege then null; end;
  assert (select count(*) from public.shiftrescue_volunteers where event_id = eid) = 1;
  begin insert into public.shiftrescue_volunteers(event_id,id,name,skills,availability,max_hours,position) values(eid,'v2','Forbidden','{}','[[0,1440]]',24,1); raise exception 'Viewer inserted volunteer'; exception when insufficient_privilege then null; end;
  begin insert into public.shiftrescue_shifts(event_id,id,station,start_min,end_min,required,skills,position) values(eid,'s2','Forbidden',60,120,1,'{}',1); raise exception 'Viewer inserted shift'; exception when insufficient_privilege then null; end;
  begin insert into public.shiftrescue_assignments(event_id,shift_id,volunteer_id,position) values(eid,'s1','v1',0); raise exception 'Viewer inserted assignment'; exception when insufficient_privilege then null; end;
  update public.shiftrescue_volunteers set name = 'Forbidden' where event_id = eid; assert not found, 'Viewer edited volunteer';
  delete from public.shiftrescue_assignments where event_id = eid; assert not found, 'Viewer deleted assignments';
  begin insert into public.shiftrescue_activity(event_id,version,kind,title,description,source) values(eid,3,'setup','Forged','Forbidden','team'); raise exception 'Viewer forged activity'; exception when insufficient_privilege then null; end;
  begin insert into shiftrescue_private.event_members(event_id,user_id,role) values(eid,viewer_uid,'editor'); raise exception 'Self promotion'; exception when insufficient_privilege then null; end;
  begin perform public.shiftrescue_set_event_deleted(eid, version_now, true); raise exception 'Viewer deleted'; exception when sqlstate 'PT404' then null; end;
  result := public.shiftrescue_request_access(code, 'editor'); assert result->>'status' = 'pending';
  assert public.shiftrescue_load_event(eid)->>'role' = 'viewer', 'Upgrade request lost current access';
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  perform public.shiftrescue_decide_access(eid, viewer_uid, 'reject');
  perform set_config('request.jwt.claim.sub', viewer_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', viewer_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid)->>'role' = 'viewer', 'Rejected upgrade removed view access';
  perform set_config('request.jwt.claim.sub', editor_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', editor_uid, 'is_anonymous', false)::text, true);
  perform public.shiftrescue_request_access(code, 'editor');
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  perform public.shiftrescue_decide_access(eid, editor_uid, 'editor');
  perform set_config('request.jwt.claim.sub', editor_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', editor_uid, 'is_anonymous', false)::text, true);
  result := public.shiftrescue_load_event(eid); version_now := (result->>'version')::bigint; assert result->>'role' = 'editor';
  result := public.shiftrescue_save_event(eid, version_now, state || '{"event":"Edited collaboratively"}', '{"kind":"setup","title":"Team updated","text":"Editor change","source":"team"}');
  assert result->'state'->>'event' = 'Edited collaboratively';
  assert result->'state'->'history'->0->>'actor' = 'Editor test', 'Actor attribution missing';
  begin perform public.shiftrescue_save_event(eid, version_now, state, null); raise exception 'Stale overwrite'; exception when sqlstate 'PT409' then null; end;
  begin update public.shiftrescue_events set owner_id = editor_uid where id = eid; raise exception 'Editor stole ownership'; exception when insufficient_privilege then null; end;
  begin update public.shiftrescue_events set deleted_at = now() where id = eid; raise exception 'Editor deleted directly'; exception when insufficient_privilege then null; end;
  begin perform public.shiftrescue_decide_access(eid, stranger_uid, 'editor'); raise exception 'Editor approved members'; exception when insufficient_privilege then null; end;
  assert not shiftrescue_private.can_read_shared_avatar(photo), 'Editor viewed another member photo';
  perform set_config('request.jwt.claim.sub', stranger_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', stranger_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid) is null;
  perform public.shiftrescue_request_access(code, 'viewer');
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  perform public.shiftrescue_decide_access(eid, stranger_uid, 'reject');
  perform public.shiftrescue_decide_access(eid, editor_uid, 'viewer');
  result := public.shiftrescue_event_sharing(eid); old_code := result->>'code';
  result := public.shiftrescue_rotate_event_code(eid); assert result->>'code' <> old_code;
  perform public.shiftrescue_decide_access(eid, viewer_uid, 'remove');
  assert not shiftrescue_private.can_read_shared_avatar(photo), 'Revoked photo still visible';
  perform set_config('request.jwt.claim.sub', viewer_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', viewer_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid) is null, 'Revoked member read event';
  assert (public.shiftrescue_request_access(old_code, 'viewer')->>'status')::integer = 404, 'Old code still works';
  perform set_config('request.jwt.claim.sub', editor_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', editor_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid)->>'role' = 'viewer', 'Editor downgrade did not apply';
  begin perform public.shiftrescue_save_event(eid, 1, state, null); raise exception 'Demoted editor saved'; exception when insufficient_privilege then null; end;
  perform set_config('request.jwt.claim.sub', owner_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', owner_uid, 'is_anonymous', false)::text, true);
  result := public.shiftrescue_load_event(eid); version_now := (result->>'version')::bigint;
  perform public.shiftrescue_set_event_deleted(eid, version_now, true);
  perform set_config('request.jwt.claim.sub', editor_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', editor_uid, 'is_anonymous', false)::text, true);
  assert public.shiftrescue_load_event(eid) is null, 'Member accessed trashed event';
  perform set_config('request.jwt.claim.sub', stranger_uid::text, true);
  perform set_config('request.jwt.claims', jsonb_build_object('sub', stranger_uid, 'is_anonymous', false)::text, true);
  for i in 1..20 loop result := public.shiftrescue_request_access('NOT-A-VALID-CODE', 'viewer'); end loop;
  assert (result->>'status')::integer = 429, 'Invalid guesses bypassed rate limiting';
  perform set_config('request.jwt.claims', jsonb_build_object('sub', stranger_uid, 'is_anonymous', true)::text, true);
  assert public.shiftrescue_load_event(eid) is null;
  begin perform public.shiftrescue_request_access(code, 'viewer'); raise exception 'Anonymous requester'; exception when sqlstate '28000' then null; end;
  reset role;
end;
$$;
select 'Owner, viewer, editor, stranger and anonymous roles: requests, profile privacy, approvals, rejection, upgrade, demotion, revocation, code rotation, actor attribution, stale saves and deletion checked; transaction rolled back.' as result;
